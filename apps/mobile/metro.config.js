const { getSentryExpoConfig } = require('@sentry/react-native/metro');
const { withUniwindConfig } = require('uniwind/metro');

/**
 * Sentry's Metro wrapper replaces the default serializer so that a Debug ID is
 * embedded in each bundle. Without it, uploaded source maps cannot be matched to
 * a crashing bundle and every stack trace arrives minified (FR-073).
 */
const config = getSentryExpoConfig(__dirname);

/**
 * Drizzle's generated `src/db/migrations/migrations.js` imports each `.sql`
 * migration; Metro must treat the extension as source so the import resolves,
 * and babel.config.js (`inline-import`) then replaces it with the file's text
 * (https://orm.drizzle.team/docs/connect-expo-sqlite).
 */
config.resolver.sourceExts.push('sql');

/**
 * Keep test files out of the app bundle.
 *
 * expo-router treats EVERY file under `src/app/` as a route, so a colocated
 * `*.test.tsx` there is bundled as though it were a screen. That drags the
 * testing library — and through it Node built-ins such as `console` — into the
 * native runtime, and the build fails with "the native React runtime does not
 * include the Node standard library".
 *
 * Tests for routes therefore live in `test/app/`. This block list is the guard
 * that stops the mistake recurring anywhere in the tree.
 */
const TEST_FILE_PATTERN = /.*\.(test|spec)\.(ts|tsx|js|jsx)$/;

const existingBlockList = config.resolver.blockList;
config.resolver.blockList = existingBlockList
  ? // Merge rather than clobber: the Expo/Sentry defaults exclude things this
    // project still needs excluded.
    new RegExp(
      `(${[]
        .concat(existingBlockList)
        .map((pattern) => pattern.source)
        .join('|')}|${TEST_FILE_PATTERN.source})`,
    )
  : TEST_FILE_PATTERN;

/**
 * Uniwind (Tailwind v4 for React Native, feature 004, research D4-02).
 *
 * It MUST be the outermost wrapper (https://docs.uniwind.dev/quickstart): it
 * replaces `transformerPath` and `resolver.resolveRequest`, so anything applied
 * after it would drop the className transform. Everything above (Sentry's Debug
 * ID serializer, the `.sql` extension, the test-file block list) is plain data
 * on `config` and survives the spread.
 *
 * - `cssEntryFile` is relative to the project root and also the root from which
 *   Tailwind scans for class names, so it lives in `src/` beside the code.
 * - `dtsFile` is generated by Metro on each run; TypeScript picks it up from
 *   `src/` through tsconfig's `include`.
 * - `extraThemes` registers the increased-contrast variants beside the built-in
 *   `light` and `dark` (research D4-05); `global.css` declares each of them.
 */
module.exports = withUniwindConfig(config, {
  cssEntryFile: './src/global.css',
  dtsFile: './src/uniwind-types.d.ts',
  extraThemes: ['light-contrast', 'dark-contrast'],
});
