/**
 * @jest-environment node
 *
 * T412 / T413 — `src/global.css`, the stylesheet Metro hands to Uniwind (research D4-02,
 * D4-04, D4-07).
 *
 * The file is wiring, not design: every colour is generated from the palette
 * (`src/theme/generated/theme.css`, contract C4-5), so a literal here is a second source
 * of truth the contrast gate cannot see. What the file may hold by hand is its import
 * order and the display-face variables.
 */
import { readFileSync } from 'node:fs';
import path from 'node:path';

import {
  MOBILE_ROOT,
  androidFamilyName,
  embeddedFontPaths,
  fontNames,
} from '../config/expo-font-plugin';

const GLOBAL_CSS = path.join(MOBILE_ROOT, 'src', 'global.css');
const raw = readFileSync(GLOBAL_CSS, 'utf8');
/** The source with comments removed: prose may mention a colour, a declaration may not. */
const css = raw.replace(/\/\*[\s\S]*?\*\//g, '');

const imports = [...css.matchAll(/@import\s+['"]([^'"]+)['"]\s*;/g)].map((m) => m[1]);

/** The value of `variable` in the first block that opens with `opener`, or undefined. */
function declared(opener: string, variable: string): string | undefined {
  const start = css.indexOf(opener);
  if (start < 0) return undefined;
  const body = css.slice(start, css.indexOf('}', start));
  return new RegExp(`${variable}:\\s*([^;]+);`).exec(body)?.[1].trim();
}

describe('src/global.css — nothing hand-written but wiring (contract C4-5)', () => {
  test('holds no colour literal: hex, oklch, rgb, hsl, color-mix', () => {
    expect(css).not.toMatch(/#[0-9a-fA-F]{3,8}\b/);
    expect(css).not.toMatch(/\b(?:oklch|oklab|lab|lch|rgba?|hsla?|hwb|color-mix)\(/);
  });

  test('declares no theme of its own: light, dark and the contrast themes are generated', () => {
    expect(css).not.toMatch(/@variant\s+(?:light|dark)/);
    expect(css).not.toContain('-contrast');
  });

  test('imports Tailwind, Uniwind, the kit, then the generated theme, in that order', () => {
    expect(imports).toEqual([
      'tailwindcss',
      'uniwind',
      'heroui-native/styles',
      './theme/generated/theme.css',
    ]);
  });

  test('puts the generated theme after the kit, so its variables win the cascade', () => {
    expect(imports.indexOf('./theme/generated/theme.css')).toBeGreaterThan(
      imports.indexOf('heroui-native/styles'),
    );
  });

  test('keeps every @import first: CSS ignores one that follows another rule', () => {
    const lastImport = css.lastIndexOf('@import');
    const before = css.slice(0, css.indexOf(';', lastImport) + 1);
    expect(before.replace(/@import\s+['"][^'"]+['"]\s*;/g, '').trim()).toBe('');
  });

  test('the generated file it imports exists', () => {
    const generated = path.join(
      path.dirname(GLOBAL_CSS),
      'theme',
      'generated',
      'theme.css',
    );
    expect(readFileSync(generated, 'utf8')).toContain('GENERATED by');
  });
});

describe('src/global.css — the display face (research D4-07)', () => {
  test('defines --font-display and --font-display-bold in @theme static', () => {
    // `static` emits them although no class uses them yet: a native header cannot take a
    // className, so it reads the family with `useCSSVariable('--font-display')`.
    expect(declared('@theme static {', '--font-display')).toBeDefined();
    expect(declared('@theme static {', '--font-display-bold')).toBeDefined();
  });

  test('leaves the kit body families alone: the interface stays in the system face', () => {
    for (const weight of ['normal', 'medium', 'semibold', 'bold']) {
      expect(css).not.toMatch(new RegExp(`--font-${weight}\\s*:`));
    }
  });

  describe('each family name is the one the platform registers for the embedded file', () => {
    const [semibold, bold] = embeddedFontPaths().map((file) =>
      path.resolve(MOBILE_ROOT, file),
    );

    test('Android answers to the file name without its extension', () => {
      expect(declared('@theme static {', '--font-display')).toBe(
        `'${androidFamilyName(semibold)}'`,
      );
      expect(declared('@theme static {', '--font-display-bold')).toBe(
        `'${androidFamilyName(bold)}'`,
      );
    });

    test('iOS answers to the name inside the file, which is its PostScript name', () => {
      // `@variant ios` inside `@layer theme { :root { } }` is Uniwind's documented
      // platform override (https://docs.uniwind.dev/faq.md, "Platform-Specific Fonts").
      expect(declared('@variant ios {', '--font-display')).toBe(
        `'${fontNames(semibold).postScript}'`,
      );
      expect(declared('@variant ios {', '--font-display-bold')).toBe(
        `'${fontNames(bold).postScript}'`,
      );
    });

    test('the two platforms really do differ, which is why the override exists', () => {
      expect(fontNames(semibold).postScript).not.toBe(androidFamilyName(semibold));
      expect(fontNames(bold).postScript).not.toBe(androidFamilyName(bold));
    });
  });
});
